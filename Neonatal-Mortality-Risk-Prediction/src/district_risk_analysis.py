"""
Create district comparison charts from outputs generated by train_model.py.

Run from project root:
    python src/district_risk_analysis.py
"""
from pathlib import Path
import pandas as pd
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "outputs"
COLORS = {"High": "#c43c39", "Medium": "#e6a23c", "Low": "#3a8d5d"}


def plot_stage(path: Path, stage: str):
    if not path.exists():
        raise FileNotFoundError(f"Missing {path}. Run src/train_model.py first.")
    df = pd.read_csv(path)
    required = {"District", "mean_risk", "national_mean_risk", "diff", "level",
                "births", "observed_deaths", "observed_rate_per_1000"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"{path.name} is missing columns: {sorted(missing)}")

    means = df["national_mean_risk"].dropna().unique()
    if len(means) != 1:
        raise ValueError("Expected one shared national mean per stage file.")
    national_mean = float(means[0])

    print(f"\n{stage.title()} stage")
    print(f"National mean predicted risk (same reference for every district): {national_mean:.3%}")
    print(df[[
        "District", "births", "observed_deaths", "observed_rate_per_1000",
        "mean_risk", "diff", "level"
    ]].round(3).to_string(index=False))

    plot_df = df.sort_values("mean_risk", ascending=True)
    fig, ax = plt.subplots(figsize=(11, 9))
    ax.barh(
        plot_df["District"],
        plot_df["diff"],
        color=plot_df["level"].map(COLORS),
    )
    ax.axvline(0, color="black", linewidth=1, linestyle="--")
    ax.set_xlabel("Difference from national mean predicted risk (percentage points)")
    ax.set_title(
        f"{stage.title()}-stage district predictions compared with national mean\n"
        f"National mean predicted risk = {national_mean:.2%}"
    )
    ax.grid(axis="x", alpha=0.2)
    fig.tight_layout()
    output_path = OUTPUTS / f"{stage}_district_risk_comparison.png"
    fig.savefig(output_path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    print(f"Chart saved to: {output_path}")


def main():
    plot_stage(OUTPUTS / "pregnancy_district_risk.csv", "pregnancy")
    plot_stage(OUTPUTS / "delivery_district_risk.csv", "delivery")
    print(
        "\nInterpretation: the national mean is shared by all districts within a stage. "
        "District means differ because records have different input profiles. High/Medium/Low "
        "are relative ranking bands (top/middle/bottom third), not clinical classifications. "
        "Observed rates are descriptive and unweighted."
    )


if __name__ == "__main__":
    main()
